def get_disease_info(disease_name):
    """
    Returns disease information for the given disease.
    Handles case-insensitive and whitespace-tolerant lookups
    (e.g. "pneumonia", "PNEUMONIA", " Pneumonia " all resolve
    to the same entry).
    """
    if not disease_name:
        return {
            "description": "Information not available.",
            "symptoms": [],
            "causes": [],
            "treatment": [],
            "prevention": []
        }

    normalized = disease_name.strip().lower()
    lookup = {key.lower(): key for key in DISEASE_INFO}
    matched_key = lookup.get(normalized)

    return DISEASE_INFO.get(
        matched_key,
        {
            "description": "Information not available.",
            "symptoms": [],
            "causes": [],
            "treatment": [],
            "prevention": []
        }
    )


